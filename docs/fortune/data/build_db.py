def sheet(name, headers, rows, widths, review=True, wrap_cols=()):
    ws = wb.create_sheet(name)
    hs = list(headers) + (['검토', '메모'] if review else [])
    ws.append(hs)
    for r in rows:
        ws.append(list(r) + (['', ''] if review else []))
    for c, h in enumerate(hs, 1):
        cell = ws.cell(1, c)
        cell.font = Font(name=FONT, bold=True, color='FFFFFF', size=10)
        cell.fill = HEAD_FILL
        cell.alignment = Alignment(horizontal='center', vertical='center', wrap_text=True)
        cell.border = BORDER
    for row in ws.iter_rows(min_row=2, max_row=ws.max_row):
        for cell in row:
            cell.font = Font(name=FONT, size=10)
            cell.border = BORDER
            cell.alignment = Alignment(vertical='center', wrap_text=cell.column in wrap_cols)
    ws.row_dimensions[1].height = 30
    allw = list(widths) + ([10, 30] if review else [])
    for i, w in enumerate(allw, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    if review:
        rc = len(hs) - 1
        dv = DataValidation(type='list', formula1='"OK,수정,삭제"', allow_blank=True)
        ws.add_data_validation(dv)
        col = get_column_letter(rc)
        dv.add(f'{col}2:{col}500')
        for r in range(2, max(ws.max_row, 40) + 1):
            for c in (rc, rc + 1):
                ws.cell(r, c).fill = REVIEW_FILL
                ws.cell(r, c).border = BORDER
                ws.cell(r, c).font = Font(name=FONT, size=10)
    ws.freeze_panes = 'A2'
    return ws


