const HIST = 'tbs.lunch.hist'
export interface Ate { name: string; day: string }

export const history = () => lsGet<Ate[]>(HIST, [])
export function markAte(name: string) {
  const day = todayKey()
  const h = history().filter((x) => x.day !== day)
  lsSet(HIST, [{ name, day }, ...h].slice(0, 14))
}

/** 최근 3일 안에 먹은 메뉴는 빼고 고르기 */
function recent() {
  const cut = Date.now() - 3 * 86400000
  return new Set(history().filter((x) => new Date(x.day + 'T12:00:00').getTime() >= cut).map((x) => x.name))
}

export function candidates(cats: Cat[], tags: Tag[]) {
  const r = recent()
  const base = MENUS.filter((m) => (cats.length === 0 || cats.includes(m.cat)) && tags.every((t) => m.tags.includes(t)))
  const fresh = base.filter((m) => !r.has(m.name))
  return fresh.length ? fresh : base
}

/** 오늘의 추천 (하루 동안 같은 메뉴) */
export function todayPick(): Menu {
  const r = rng(hash('lunch' + todayKey()))
  const list = candidates([], [])
  return list[Math.floor(r() * list.length)]
}

export function randomPick(list: Menu[], not?: string): Menu {
  if (list.length === 0) return MENUS[0]
  let m = list[Math.floor(Math.random() * list.length)]
  if (list.length > 1) while (m.name === not) m = list[Math.floor(Math.random() * list.length)]
  return m
}
